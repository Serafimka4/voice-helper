def _any(patterns: list[str], u: Utterance) -> bool:
    return any(u.has(p) for p in patterns)


def check_red_flags(u: Utterance) -> Route | None:
    """R-01 и R-11 — проверяются на каждой реплике, в любом сценарии, включая исходящие."""
    if u.has(ALREADY_CALLED_AMBULANCE):
        return Route("R-01", "P1", "М0", "Хорошо. Дождитесь скорую. Если нужно, позвоните нам позже.",
                     transfer=False, result="EMERGENCY", reason="Скорая уже вызвана")
    if u.has(SELF_HARM):
        return Route("R-01", "P1", "М0+М2",
                     "Мне важно, чтобы вы были в безопасности. Пожалуйста, позвоните сто двенадцать прямо сейчас. "
                     "Я соединяю вас с сотрудником.",
                     transfer=True, result="EMERGENCY", reason="Высказывания о намерении причинить себе вред")
    if _any(RED_FLAGS_A, u):
        return Route("R-01", "P1", "М0+М2",
                     f"Пожалуйста, немедленно звоните в скорую помощь: {AMBULANCE}. Повторяю: {AMBULANCE}. "
                     "Я соединяю вас с регистратором, но не ждите — звоните в скорую сразу.",
                     transfer=True, result="EMERGENCY", reason="Красный флаг категории А")
    if u.has(DENTAL_ACUTE):
        return Route("R-09", "P2", "М4-С",
                     "Соединяю со стоматологическим отделением — вас примут в день обращения.",
                     transfer=True, result="ESCALATED", reason="Острая зубная боль")
    if _any(RED_FLAGS_B, u):
        return Route("R-11", "P1", "М2→М4-Н",
                     "Соединяю с регистратором, он организует срочную помощь. Если станет хуже — сразу звоните сто три.",
                     transfer=True, result="ESCALATED", reason="Красный флаг категории Б: острое состояние")
    return None


def check_routing(u: Utterance) -> Route | None:
    """Правила R-02…R-16, кроме медицинского вопроса (его обрабатывает диалог: сначала граничная фраза)."""
    if u.has(ROBOT):
        return Route("", "", "М1", "Да, я виртуальный помощник регистратуры. Если хотите, соединю с сотрудником.",
                     transfer=False, result="", reason="Вопрос «вы робот?»")
    if u.has(COMPLAINT):
        return Route("R-03", "P2", "М3",
                     "Мне жаль, что так вышло. Соединяю вас со старшим администратором — суть обращения уже передана, "
                     "повторять не придётся.",
                     transfer=True, result="COMPLAINT", reason="Жалоба")
    if u.has(ORGANIZATION):
        return Route("R-14", "P3", "М3", "Соединяю с администрацией.", transfer=True, result="ESCALATED",
                     reason="Звонок от организации")
    if u.has(PD_REQUEST):
        return Route("R-16", "P3", "М3", "Этот запрос оформляется письменно. Соединяю с администратором.",
                     transfer=True, result="ESCALATED", reason="Запрос субъекта персональных данных")
    if u.has(PAID_DEPT):
        return Route("R-10", "P3", "М4-П", "Соединяю с платным отделением.", transfer=True, result="ESCALATED",
                     reason="Платные услуги вне справочника, ДМС, медкомиссия")
    if u.has(OPERATOR):
        return Route("R-02", "P2", "М2", "Соединяю с сотрудником.", transfer=True, result="ESCALATED",
                     reason="Пациент попросил сотрудника")
    if u.has(REGIONAL):
        return Route("R-12", "", "М5", "Этот вопрос решает региональный колл-центр Минздрава, номер сто двадцать два.",
                     transfer=False, result="INFO_GIVEN", reason="Региональные вопросы")
    if u.has(POLICY):
        return Route("R-13", "", "М5", "Полис оформляет страховая медицинская компания. Телефон указан на полисе.",
                     transfer=False, result="INFO_GIVEN", reason="Полис ОМС")
    return None


def is_medical_question(u: Utterance) -> bool:
    return u.has(MEDICAL)


def medical_boundary_phrase(u: Utterance) -> str:
    """Универсальные ответы на медицинские вопросы (раздел 3.8)."""
    if u.has(ANALYSIS_VALUES):
        return ("Я не вижу значений результатов и не могу их оценивать — это сделает врач. "
                "Результаты доступны на Госуслугах, в окне номер три с двенадцати до девятнадцати и у лечащего врача. "
                "Записать вас к терапевту?")
    return ("Я не могу давать медицинские советы — это может сделать только врач. "
            "Давайте я запишу вас на приём к терапевту. Если состояние резко ухудшилось, звоните сто три.")


